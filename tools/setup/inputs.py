#!/usr/bin/env python3
"""inputs.py: pin and verify the original game files in eob/.

  python3 tools/setup/inputs.py --check   # verify against re/inputs.toml (default)
  python3 tools/setup/inputs.py --write   # (re)write re/inputs.toml; humans only, see AGENTS.md rule 6

LEVELS.TMP and EOBDATA.SAV are written by the game while it runs (SPEC section 2), so they are
not pinned: playing the game in eob/ must not break the check.
"""
import argparse, hashlib, os, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GAME = os.path.join(ROOT, "eob")
PIN = os.path.join(ROOT, "re", "inputs.toml")
SKIP_NAMES = {".DS_Store", "LEVELS.TMP", "EOBDATA.SAV"}


def files():
    for dp, dn, fn in os.walk(GAME):
        dn.sort()
        for f in sorted(fn):
            if f in SKIP_NAMES:
                continue
            p = os.path.join(dp, f)
            yield os.path.relpath(p, ROOT).replace(os.sep, "/"), p


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not os.path.isdir(GAME):
        print("missing: eob/ (the original game files)")
        return 1
    if a.write:
        out = ["# Pinned original inputs. Generated by tools/setup/inputs.py --write.",
               "# Changing this file changes the target of the whole project (AGENTS.md rule 6).", ""]
        for rel, p in files():
            out += ['[file."%s"]' % rel, "bytes = %d" % os.path.getsize(p), 'sha256 = "%s"' % sha(p), ""]
        open(PIN, "w").write("\n".join(out))
        print("wrote", os.path.relpath(PIN, ROOT))
        return 0
    if not os.path.exists(PIN):
        print("missing: re/inputs.toml (run tools/setup/inputs.py --write once)")
        return 1
    pins = {k: v["sha256"] for k, v in tomllib.loads(open(PIN).read()).get("file", {}).items()}
    seen, bad = set(), 0
    for rel, p in files():
        seen.add(rel)
        if rel not in pins:
            print("extra   " + rel); bad += 1
        elif sha(p) != pins[rel]:
            print("CHANGED " + rel); bad += 1
    for rel in sorted(set(pins) - seen):
        print("MISSING " + rel); bad += 1
    print("inputs: %d files pinned, %s" % (len(pins), "OK" if not bad else "%d problems" % bad))
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
