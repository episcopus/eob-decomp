#!/usr/bin/env python3
"""cmatch.py: prove C functions against the original (L2), Phase 1 spike version (SPEC 4.2).

The C file names the original address of everything it defines or uses, in a comment on the
line of the declaration or definition:

    /*@ 0CF7:0007 */ void ListInit(struct Node far *head)     a function: seg:off in the program
    extern char gFlag; /*@ ds:F3B9 */                         a global: offset in DGROUP

The file is compiled with the pinned Turbo C++ and `cflags` of tools/re/tc_toolchain.toml (or --flags),
linked with C0L, CL.LIB
and a generated stub module that defines every extern it names (data in DGROUP, functions as
empty far functions), and every annotated function defined in the file is compared with the
original, instruction by instruction:

  - opcode bytes (everything before a displacement or immediate) must be identical;
  - a differing displacement or immediate must name the same global (ours: the DGROUP public
    at or below the value; theirs: that global's annotated offset plus the same delta);
  - a DS offset into this file's own data (a string literal) must point at the same text;
  - a far call must reach the function with the same name; a near call or jump, the same
    distance (relative fields are compared as bytes);
  - the function must end at a return on both sides with the same number of instructions.

  cmatch.py FILE.C [--program eob/EOB.EXE] [--flags="-ml -O -Z"] [--write] [-v]
--write records level L2 and the name of every matched function in re/symbols.toml.
Exit code 0 when every annotated function defined in the file matches.
"""
from __future__ import annotations

import argparse, os, re, shutil, sys
from pathlib import Path

from capstone import CS_ARCH_X86, CS_MODE_16, Cs
from capstone.x86 import X86_OP_IMM, X86_OP_MEM

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "re"))
from mzutil import read_mz  # noqa: E402
import tc_toolchain as tc  # noqa: E402

MD = Cs(CS_ARCH_X86, CS_MODE_16)
MD.detail = True
ANNOT = re.compile(r"/\*@\s*(ds:[0-9A-Fa-f]{1,4}|[0-9A-Fa-f]{4}:[0-9A-Fa-f]{4})\s*\*/")
DGROUP_EOB = 0x212E
KEYWORDS = {"void", "char", "int", "long", "short", "unsigned", "signed", "far", "near", "huge",
            "extern", "static", "struct", "union", "const", "volatile", "interrupt", "cdecl", "pascal"}


def parse_annotations(src: str) -> tuple[dict, dict, set]:
    """name -> original address for functions (linear) and globals (DS offset); defined functions."""
    funcs, data, defined = {}, {}, set()
    for line in src.splitlines():
        m = ANNOT.search(line)
        if not m:
            continue
        decl = ANNOT.sub("", line)
        fp = re.search(r"\(\s*(?:far\s*|near\s*)?\*\s*([A-Za-z_]\w*)\s*\)", decl)  # function pointer
        names = [fp.group(1)] if fp else [n for n in re.findall(r"([A-Za-z_]\w*)\s*(?:\(|\[|;|=|,)", decl)
                                          if n not in KEYWORDS]
        if not names:
            raise SystemExit("cmatch: no name on annotated line: %s" % line.strip())
        name, addr = names[0], m.group(1)
        if addr.lower().startswith("ds:"):
            data[name] = int(addr[3:], 16)
        else:
            seg, off = (int(x, 16) for x in addr.split(":"))
            funcs[name] = seg * 16 + off
            if not decl.strip().startswith("extern") and not decl.rstrip().endswith(";"):
                defined.add(name)
    return funcs, data, defined


def stub_source(funcs: dict, data: dict, defined: set) -> str:
    out = ["/* generated by tools/match/cmatch.py */"]
    for n in sorted(data):
        out.append("char %s[256];" % n)
    for n in sorted(set(funcs) - defined):
        out.append("void far %s(void) {}" % n)
    out.append("int main(void) { return 0; }")
    return "\r\n".join(out) + "\r\n"


def read_map(path: Path) -> tuple[dict, int, list, tuple]:
    publics, dgroup, segs, lits = {}, None, [], (0, 0)
    for line in path.read_text("latin-1").splitlines():
        m = re.match(r"\s*([0-9A-F]{4}):([0-9A-F]{4}) ([0-9A-F]{4}) C=DATA\s+S=_DATA\s+G=DGROUP\s+M=u\.c", line, re.I)
        if m:
            lits = (int(m.group(2), 16), int(m.group(2), 16) + int(m.group(3), 16))
        m = re.match(r"\s*([0-9A-F]{4}):([0-9A-F]{4}) ([0-9A-F]{4}) C=CODE", line)
        if m:
            s = int(m.group(1), 16) * 16 + int(m.group(2), 16)
            segs.append((s, s + int(m.group(3), 16)))
        m = re.match(r"\s*([0-9A-F]{4}):([0-9A-F]{4})\s+(?:idle\s+)?(_\w+)\s*$", line)
        if m:
            publics[m.group(3)[1:]] = int(m.group(1), 16) * 16 + int(m.group(2), 16)
        m = re.match(r"\s*([0-9A-F]{4}):([0-9A-F]{4}) [0-9A-F]{4} C=\w+\s+S=\S+\s+G=DGROUP", line)
        if m and dgroup is None:
            dgroup = int(m.group(1), 16)
    return publics, dgroup, segs, lits


def cstr(side, off: int) -> bytes:
    p = side.dgroup * 16 + off
    return side.image[p:side.image.index(b"\0", p)]


def fields(i) -> list[tuple[int, int, int, str]]:
    """(byte offset, size, value, kind) of the address-like fields of an instruction."""
    out = []
    if i.disp_offset:
        size = (i.imm_offset or i.size) - i.disp_offset
        out.append((i.disp_offset, size, int.from_bytes(i.bytes[i.disp_offset:i.disp_offset + size], "little"), "disp"))
    if i.imm_offset:
        size = i.size - i.imm_offset
        out.append((i.imm_offset, size, int.from_bytes(i.bytes[i.imm_offset:], "little"), "imm"))
    return out


class Side:
    def __init__(self, image: bytes, relocs: set, dgroup: int, lits: tuple = (0, 0)):
        self.image, self.relocs, self.dgroup, self.lits = image, relocs, dgroup, lits


def compare(name, ours_at, ours_end, theirs_at, ours: Side, theirs: Side, publics, funcs, data, verbose) -> list[str]:
    errs = []
    a = MD.disasm(ours.image[ours_at:ours_at + 4096], ours_at)
    b = MD.disasm(theirs.image[theirs_at:theirs_at + 4096], theirs_at)
    by_addr = sorted((v, k) for k, v in publics.items())
    ds_pub = sorted((v - ours.dgroup * 16, k) for k, v in publics.items() if k in data)
    n = 0
    for x, y in zip(a, b):
        n += 1
        if verbose:
            print("   %05X %-14s %-26s | %05X %-14s %s %s" % (x.address, x.bytes.hex(), x.mnemonic + " " + x.op_str,
                                                          y.address, y.bytes.hex(), y.mnemonic, y.op_str))
        if x.bytes != y.bytes:
            ok = x.size == y.size and x.mnemonic == y.mnemonic
            if ok and x.bytes[0] == 0x9A:  # far call: compare by target name
                t_ours = int.from_bytes(x.bytes[3:5], "little") * 16 + int.from_bytes(x.bytes[1:3], "little")
                t_theirs = int.from_bytes(y.bytes[3:5], "little") * 16 + int.from_bytes(y.bytes[1:3], "little")
                callee = next((k for v, k in by_addr if v == t_ours), None)
                ok = callee in funcs and funcs[callee] == t_theirs
                if not ok:
                    errs.append("%s: far call at +%04X reaches %s, original reaches %05X" % (
                        name, x.address - ours_at, callee, t_theirs))
                    break
                continue
            fx, fy = fields(x), fields(y)
            cut = min([f[0] for f in fx] or [x.size])
            ok = ok and x.bytes[:cut] == y.bytes[:cut] and len(fx) == len(fy)
            for (o1, s1, v1, k1), (o2, s2, v2, k2) in zip(fx, fy):
                if not ok:
                    break
                if v1 == v2:
                    continue
                if ours.lits[0] <= v1 < ours.lits[1]:  # a string literal of this file: same text
                    ok = cstr(ours, v1) == cstr(theirs, v2)
                    if not ok:
                        errs.append("%s: literal at +%04X is %r, original %r" % (
                            name, x.address - ours_at, cstr(ours, v1), cstr(theirs, v2)))
                    continue
                g = max(((off, nm) for off, nm in ds_pub if off <= v1), default=None)
                ok = g is not None and v1 - g[0] < 256 and data[g[1]] + (v1 - g[0]) == v2
                if not ok:
                    errs.append("%s: field at +%04X is %04X (%s), original %04X" % (
                        name, x.address - ours_at, v1, "%s+%d" % (g[1], v1 - g[0]) if g else "?", v2))
            if not ok:
                if not errs or not errs[-1].startswith(name + ": field"):
                    errs.append("%s: +%04X ours %s %s, original %s %s" % (
                        name, x.address - ours_at, x.mnemonic, x.op_str, y.mnemonic, y.op_str))
                break
        if x.address + x.size >= ours_end:
            if x.mnemonic not in ("ret", "retf", "iret", "jmp"):
                errs.append("%s: our function does not end with a return" % name)
            return errs
    else:
        errs.append("%s: ran out of instructions after %d" % (name, n))
    return errs


def write_levels(names_by_linear: dict, flags: str) -> int:
    """Set name and level = "L2" on the registry entries of matched functions (EOB.EXE resident)."""
    p = ROOT / "re" / "symbols.toml"
    blocks = p.read_text().split("[[function]]\n")
    n = 0
    for i, b in enumerate(blocks):
        m = re.search(r'^addr = "([0-9A-F]{4}):([0-9A-F]{4})"$', b, re.M)
        if not m or not re.search(r'^unit = "e', b, re.M):
            continue
        name = names_by_linear.get(int(m.group(1), 16) * 16 + int(m.group(2), 16))
        if not name:
            continue
        b = re.sub(r'^(name|level|match_flags) = .*\n', "", b, flags=re.M)
        blocks[i] = b.rstrip("\n") + '\nname = "%s"\nlevel = "L2"\nmatch_flags = "%s"\n\n' % (name, flags)
        n += 1
    p.write_text("[[function]]\n".join(blocks))
    return n


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("file")
    ap.add_argument("--program", default=str(ROOT / "eob" / "EOB.EXE"))
    ap.add_argument("--dgroup", type=lambda s: int(s, 16), default=DGROUP_EOB)
    ap.add_argument("--flags", default=None)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--release", default=None)
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()
    release = a.release or tc.manifest()["pinned"]
    flags = (a.flags if a.flags is not None else tc.manifest()["cflags"]).split()
    src = Path(a.file).read_text()
    funcs, data, defined = parse_annotations(src)
    w = ROOT / "build" / "match" / Path(a.file).stem
    shutil.rmtree(w, ignore_errors=True)
    w.mkdir(parents=True)
    (w / "U.C").write_text(src.replace("\r\n", "\n").replace("\n", "\r\n"))
    (w / "STUB.C").write_text(stub_source(funcs, data, defined))
    for f in ("U.C", "STUB.C"):
        r = tc.run(release, "TCC", ["-c", "-ID:\\INCLUDE"] + flags + [f], cwd=w)
        out = r.stdout.decode("latin-1")
        if not (w / (f[:-2] + ".OBJ")).exists() or "Error" in out:
            print(out)
            return 1
    r = tc.run(release, "TLINK", ["/c", "/m", "/s", "D:\\LIB\\C0L+STUB+U,P,P,D:\\LIB\\CL"], cwd=w)
    if not (w / "P.EXE").exists():
        print(r.stdout.decode("latin-1"))
        return 1
    mz = read_mz((w / "P.EXE").read_bytes())
    publics, dgroup, segs, lits = read_map(w / "P.MAP")
    ours = Side(mz["image"], {s * 16 + o for o, s in mz["relocs"]}, dgroup, lits)
    tz = read_mz(open(a.program, "rb").read())
    theirs = Side(tz["image"], {s * 16 + o for o, s in tz["relocs"]}, a.dgroup)
    bad, matched = 0, []
    for name in sorted(defined, key=lambda n: funcs[n]):
        if name not in publics:
            print("MISSING %s: not public in our build (static?)" % name)
            bad += 1
            continue
        at = publics[name]
        seg_end = next(e for s, e in segs if s <= at < e)
        end = min([publics[n] for n in defined if n in publics and at < publics[n] < seg_end] + [seg_end])
        errs = compare(name, at, end, funcs[name], ours, theirs, publics, funcs, data, a.verbose)
        print(("ok      %s at linear %05X" % (name, funcs[name])) if not errs else
              "DIFFER  " + errs[0])
        bad += bool(errs)
        if not errs:
            matched.append(name)
    print("cmatch: %d of %d functions match" % (len(defined) - bad, len(defined)))
    if a.write and Path(a.program).name.upper() == "EOB.EXE":
        n = write_levels({funcs[k]: k for k in matched}, " ".join(flags))
        print("cmatch: recorded L2 for %d functions in re/symbols.toml" % n)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
