#!/usr/bin/env python3
"""map_units.py: the per-module map (re/units.toml) and the function registry (re/symbols.toml).

Inputs, all regenerated by `make map`: build/re/<prog>.json (fbov.py), build/re/<prog>-functions.json
(functions.py), build/re/rtl_compare.json and rtl_intro.json (rtl_compare.py, optional).

Units:
  - one per non-empty code segment of EOB.EXE and INTRO.EXE (Turbo C++ large model gives every
    source module its own code segment), id <program letter><frame paragraph>, e.g. e0cf7;
  - segment 0 (_TEXT) is split into the startup (C0L), the assembly modules that use _TEXT,
    and the runtime library, at the boundaries rtl_compare.py found;
  - one per overlaid segment, id <letter>ov<n>;
  - START1.EXE is one unit until it is mapped.
kind: c, asm, unknown (by the shape of the functions, [H] until matched), library, startup.
An INTRO.EXE unit whose code is the same as an EOB.EXE unit's (address fields aside) is marked
`same_as`: it is decompiled once.

Existing names, signatures, levels and notes in re/symbols.toml are kept (by id).

  map_units.py [--write]     without --write: print the summary only
"""
from __future__ import annotations

import argparse, json, os, sys, tomllib
from pathlib import Path

from capstone import CS_ARCH_X86, CS_MODE_16, Cs

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mzutil import read_mz  # noqa: E402
from rtl_compare import same_insn  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RE = ROOT / "re"
BUILD = ROOT / "build" / "re"
MD = Cs(CS_ARCH_X86, CS_MODE_16)
MD.detail = True
PROGRAMS = [("e", "EOB.EXE", "eob"), ("i", "INTRO.EXE", "intro")]
KEEP = ("name", "signature", "level", "match_flags", "notes", "review")


def c_like(img: bytes, at: int) -> bool:
    ins = list(MD.disasm(img[at:at + 40], 0))[:6]
    if len(ins) < 3 or (ins[0].mnemonic, ins[0].op_str) != ("push", "bp") or ins[1].op_str != "bp, sp":
        return False
    return not any(i.mnemonic == "push" and i.op_str in ("ax", "bx", "cx", "dx", "ds", "es") for i in ins[2:5])


def classify(img: bytes, start: int, size: int, funcs: list) -> str:
    ins = list(MD.disasm(img[start:start + size], 0))
    if sum(i.size for i in ins) < size * 0.95 or any(i.mnemonic == "iret" for i in ins):
        return "asm"
    if sum(i.mnemonic == "ret" for i in ins) > 1:
        return "asm"
    c = sum(c_like(img, f["linear"]) for f in funcs)
    if funcs and c >= 0.75 * len(funcs) and (size >= 400 or c == len(funcs) >= 3):
        return "c"
    return "asm" if c <= len(funcs) // 2 else "unknown"


def same_code(a: bytes, b: bytes) -> bool:
    x, y = list(MD.disasm(a, 0)), list(MD.disasm(b, 0))
    return len(x) == len(y) and sum(i.size for i in x) == len(a) and all(same_insn(p, q) for p, q in zip(x, y))


def lib_start(path: Path, default: int | None) -> int | None:
    if not path.exists():
        return default
    found = json.loads(path.read_text())["tc100"]["found"]
    lo = [v for k, v in found.items() if v >= 0x20C]
    return min(lo) if lo else default


def build() -> tuple[list, list]:
    units, funcs = [], []
    images = {}
    for letter, exe, stem in PROGRAMS:
        mz = read_mz((ROOT / "eob" / exe).read_bytes())
        img = mz["image"]
        images[letter] = img
        man = json.loads((BUILD / ("%s.json" % stem)).read_text())
        fn = json.loads((BUILD / ("%s-functions.json" % stem)).read_text())
        libs = lib_start(BUILD / ("rtl_compare.json" if letter == "e" else "rtl_intro.json"), None)
        for s in man["segments"]:
            if s["kind"] != 1 or not s["size"]:
                continue
            start, end, para = s["start"], s["start"] + s["size"], s["para"]
            fs = [f for f in fn["resident"] if start <= f["linear"] < end]
            parts = [(start, end, "%s%04x" % (letter, para), None)]
            if para == 0:
                parts = [(0, 0x20C, letter + "_c0", "startup")]
                if libs:
                    parts += [(0x20C, libs, letter + "_text", "asm"), (libs, end, letter + "_lib", "library")]
                else:
                    parts += [(0x20C, end, letter + "_text", "unknown")]
            for a, b, uid, kind in parts:
                pf = [f for f in fs if a <= f["linear"] < b]
                units.append({"id": uid, "program": exe, "segment": "%04X" % para,
                              "start": "%04X:%04X" % (para, a - para * 16), "linear": a, "bytes": b - a,
                              "functions": len(pf), "kind": kind or classify(img, a, b - a, pf)})
                for f in pf:
                    funcs.append({"id": "%s_%04x" % (uid if para else letter + "0000", f["offset"]), "unit": uid,
                                  "addr": "%04X:%04X" % (para, f["offset"]), "size": f["size"],
                                  "evidence": f["evidence"]})
        for o in man["overlays"]:
            uid = "%sov%d" % (letter, o["overlay"])
            ofs = [f for f in fn["overlay"] if f["overlay"] == o["overlay"]]
            code = (BUILD / ("%s-overlays" % stem) / ("ovl%02d.bin" % o["overlay"])).read_bytes()
            kind = classify(code, 0, len(code), [{"linear": f["offset"]} for f in ofs])
            units.append({"id": uid, "program": exe, "segment": "%04X" % o["stub_para"], "overlay": o["overlay"],
                          "start": "ovl%d:0000" % o["overlay"], "bytes": o["code_bytes"],
                          "functions": len(ofs), "kind": kind})
            for f in ofs:
                funcs.append({"id": "%s_%04x" % (uid, f["offset"]), "unit": uid,
                              "addr": "ovl%d:%04X" % (o["overlay"], f["offset"]), "size": f["size"],
                              "evidence": f["evidence"]})
    # START1.EXE is small model (C0S, CS.LIB; 2026-11-03): no overlays, so no segment table; all code is
    # one segment, 0000 to DGROUP (01AA, the start-up code's relocated word at 0000:0001). C0.ASM is
    # 0239h bytes (the small-model reference link's map) and the library starts at its first module
    # found by rtl_compare (build/re/rtl_start1.json, OVRHP at 0574h); Westwood's code lies between.
    s1 = read_mz((ROOT / "eob" / "START1.EXE").read_bytes())
    s1lib = lib_start(BUILD / "rtl_start1.json", 0x574)
    fn = json.loads((BUILD / "start1-functions.json").read_text()) if (BUILD / "start1-functions.json").exists() else {"resident": []}
    for uid, a, b, kind in (("s_c0", 0, 0x239, "startup"), ("s_text", 0x239, s1lib, "unknown"), ("s_lib", s1lib, 0x1AA0, "library")):
        pf = [f for f in fn["resident"] if a <= f["linear"] < b]
        units.append({"id": uid, "program": "START1.EXE", "segment": "0000", "start": "0000:%04X" % a, "linear": a,
                      "bytes": b - a, "functions": len(pf), "kind": kind})
        for f in pf:
            funcs.append({"id": "s0000_%04x" % f["linear"], "unit": uid, "addr": "0000:%04X" % f["linear"],
                          "size": min(f["size"], b - f["linear"]), "evidence": f["evidence"]})
    # INTRO units that are EOB units
    eob = [u for u in units if u["program"] == "EOB.EXE" and "linear" in u and u["kind"] != "library"]
    for u in units:
        if u["program"] != "INTRO.EXE" or "linear" not in u or u["kind"] in ("library", "startup"):
            continue
        a = images["i"][u["linear"]:u["linear"] + u["bytes"]]
        for e in eob:
            if e["bytes"] == u["bytes"] and same_code(a, images["e"][e["linear"]:e["linear"] + e["bytes"]]):
                u["same_as"] = e["id"]
                break
    return units, funcs


def q(v) -> str:
    if isinstance(v, str):
        return '"%s"' % v.replace("\\", "\\\\").replace('"', '\\"')
    if isinstance(v, list):
        return "[" + ", ".join(q(x) for x in v) + "]"
    return str(v).lower() if isinstance(v, bool) else str(v)


def write(units: list, funcs: list) -> None:
    old = {}
    p = RE / "symbols.toml"
    if p.exists():
        old = {f["id"]: f for f in tomllib.loads(p.read_text()).get("function", [])}
    out = ["# Units: one per code segment (module) of each program. Generated by tools/re/map_units.py",
           "# (`make map`); kind is [H] until the unit's code is matched. See re/README.md.", ""]
    for u in units:
        out.append("[[unit]]")
        out += ["%s = %s" % (k, q(v)) for k, v in u.items() if k != "linear"]
        out.append("")
    (RE / "units.toml").write_text("\n".join(out))
    out = ["# Functions. Generated by tools/re/map_units.py (`make map`); name, signature, level, notes and",
           "# review are kept across runs. size is the distance to the next known start (see functions.py).", ""]
    for f in funcs:
        f = dict(f, **{k: old[f["id"]][k] for k in KEEP if f["id"] in old and k in old[f["id"]]})
        out.append("[[function]]")
        out += ["%s = %s" % (k, q(v)) for k, v in f.items()]
        out.append("")
    p.write_text("\n".join(out))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    units, funcs = build()
    from collections import Counter
    for prog in ("EOB.EXE", "INTRO.EXE", "START1.EXE"):
        us = [u for u in units if u["program"] == prog]
        kinds = Counter(u["kind"] for u in us)
        shared = sum(1 for u in us if "same_as" in u)
        print("%s: %d units (%s)%s, %d functions" % (
            prog, len(us), ", ".join("%d %s" % (v, k) for k, v in sorted(kinds.items())),
            ", %d same as an EOB.EXE unit" % shared if shared else "", sum(u["functions"] for u in us)))
    if a.write:
        write(units, funcs)
        print("wrote re/units.toml, re/symbols.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
